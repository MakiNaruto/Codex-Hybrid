"""Pure Codex TOML transformations shared by CLI and management routing.

Functions preserve unrelated fields and comments and reject unsafe rewrites.
Filesystem writes, configuration locks and OS lifecycle calls belong to callers.
"""
import copy
import hashlib
import json
import re
import tomllib

from model_catalog.catalog import ConfigError


PROVIDER = 'codex-hybrid'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def is_bridge_provider(provider):
    fields = {'name', 'base_url', 'wire_api', 'requires_openai_auth',
              'supports_websockets', 'request_max_retries', 'stream_max_retries',
              'http_headers'}
    headers = provider.get('http_headers', {}) if isinstance(provider, dict) else {}
    return (isinstance(provider, dict)
            and provider.get('name') == 'Codex Hybrid'
            # Recognize both the original no-retry format and the current
            # explicit Codex defaults, so upgrades and rollback stay safe.
            and ((set(provider) == fields
                  and provider.get('request_max_retries') == 0
                  and provider.get('stream_max_retries') == 0)
                 or (set(provider) == fields | {'stream_idle_timeout_ms'}
                     and provider.get('request_max_retries') == 4
                     and provider.get('stream_max_retries') == 5
                     and provider.get('stream_idle_timeout_ms') == 300000))
            and str(provider.get('base_url', '')).startswith('http://127.0.0.1:')
            and provider.get('wire_api') == 'responses'
            and provider.get('requires_openai_auth') is True
            and provider.get('supports_websockets') is False
            and isinstance(headers, dict)
            and set(headers) == {'X-Connected-Token'}
            and isinstance(headers['X-Connected-Token'], str)
            and bool(headers['X-Connected-Token']))


def remove_bridge_provider_table(original):
    """Remove only the provider table generated by this application."""
    parsed = tomllib.loads(original)
    providers = parsed.get('model_providers', {})
    provider = providers.get(PROVIDER) if isinstance(providers, dict) else None
    if provider is None:
        return original, False
    if not is_bridge_provider(provider):
        raise ValueError('Codex 配置中的 codex-hybrid provider 不是本项目生成的格式，未移除。')
    split = re.search(r'^\s*\[', original, re.MULTILINE)
    boundary = split.start() if split else len(original)
    root, tables = original[:boundary], original[boundary:]
    header = re.compile(
        r'^\[model_providers\.(?:"codex-hybrid"|codex-hybrid)\]\s*(?:#.*)?$',
        re.MULTILINE)
    match = header.search(tables)
    if not match:
        raise ValueError('无法安全定位 Codex Hybrid provider 配置，未移除。')
    following = re.search(r'^\s*\[', tables[match.end():], re.MULTILINE)
    end = match.end() + following.start() if following else len(tables)
    result = root + tables[:match.start()] + tables[end:]
    after = tomllib.loads(result)
    expected = copy.deepcopy(parsed)
    expected['model_providers'].pop(PROVIDER)
    if not expected['model_providers']:
        expected.pop('model_providers')
    if after != expected:
        raise ValueError('移除 Codex Hybrid provider 时发现其他配置变化，未移除。')
    return result, True


def candidate_config(original, settings):
    parsed = tomllib.loads(original)
    if parsed.get('profile'):
        raise ValueError('Codex 配置启用了 profile，请先关闭 profile 再安装。')
    existing_provider = parsed.get('model_providers', {}).get(PROVIDER)
    if existing_provider is not None and not is_bridge_provider(existing_provider):
        raise ValueError('Codex 配置中已有同名 provider，但无法确认由本项目生成；请先检查后再安装。')
    if existing_provider is not None:
        original, _ = remove_bridge_provider_table(original)
        parsed = tomllib.loads(original)
    marker = '# Codex Hybrid; rollback with ./scripts/codex-hybrid.sh rollback'
    original = re.sub(r'(?m)^' + re.escape(marker) + r'[ \t]*(?:\r?\n|$)', '', original)
    # Root values only; preserve unrelated tables, comments and configuration.
    split = re.search(r'^\s*\[', original, re.MULTILINE)
    boundary = split.start() if split else len(original)
    root, tables = original[:boundary], original[boundary:]
    for key in ['model_provider', 'model_catalog_json']:
        root = re.sub(r'^' + key + r'\s*=.*(?:\n|$)', '', root, flags=re.MULTILINE)
    # Normalize only the separators we own. Without this, removing the old
    # provider and adding a fresh one on every activation accumulates blank
    # lines around the root/table boundary.
    root = root.rstrip('\r\n')
    tables = tables.strip('\r\n')
    result = ('# Codex Hybrid; rollback with ./scripts/codex-hybrid.sh rollback\n'
              f'model_provider = "{PROVIDER}"\nmodel_catalog_json = {json.dumps(settings["catalog"])}\n' +
              root + ('\n' if root else '') +
              (tables + '\n' if tables else '') +
              f'\n[model_providers.{PROVIDER}]\nname = "Codex Hybrid"\n'
              f'base_url = "http://127.0.0.1:{settings["port"]}"\n'
              'wire_api = "responses"\nrequires_openai_auth = true\nsupports_websockets = false\n'
              'request_max_retries = 4\nstream_max_retries = 5\nstream_idle_timeout_ms = 300000\n'
              f'http_headers = {{ "X-Connected-Token" = {json.dumps(settings["local_token"])} }}\n')
    legacy_plugin = 'connected-models@connected-local'
    disable_legacy = settings.get('disable_legacy_plugin', True) and legacy_plugin in parsed.get('plugins', {})
    if disable_legacy:
        pattern = r'(?ms)^(\[plugins\.["\x27]connected-models@connected-local["\x27]\][^\S\n]*\n)(.*?)(?=^\s*\[|\Z)'
        def disable(match):
            body = match[2]
            if re.search(r'^enabled\s*=', body, re.MULTILINE):
                body = re.sub(r'^enabled\s*=.*$', 'enabled = false', body, count=1, flags=re.MULTILINE)
            else:
                body = 'enabled = false\n' + body
            return match[1] + body
        result, count = re.subn(pattern, disable, result)
        if count != 1:
            raise ValueError('Cannot safely disable the legacy Connected MCP plugin')
    after = tomllib.loads(result)
    # Reject tricky multiline rewrites or any unintended semantic change.
    comparable = copy.deepcopy(after)
    comparable.pop('model_provider')
    comparable.pop('model_catalog_json')
    comparable['model_providers'].pop(PROVIDER)
    if not comparable['model_providers']:
        comparable.pop('model_providers')
    expected = copy.deepcopy(parsed)
    expected.pop('model_provider', None)
    expected.pop('model_catalog_json', None)
    expected.get('model_providers', {}).pop(PROVIDER, None)
    if expected.get('model_providers') == {}:
        expected.pop('model_providers')
    if disable_legacy:
        expected['plugins'][legacy_plugin]['enabled'] = False
    if comparable != expected:
        raise ValueError('Configuration rewrite changed unrelated settings')
    return result


ROOT_KEYS = ('model_provider', 'model_catalog_json')


def managed(config):
    return {**{key: config.get(key) for key in ROOT_KEYS},
            'provider': config.get('model_providers', {}).get(PROVIDER)}


def restore(current, baseline):
    """Restore owned fields while retaining unrelated user edits and comments."""
    before = tomllib.loads(current)
    native = tomllib.loads(baseline)
    result, _ = remove_bridge_provider_table(current)
    boundary = re.search(r'^\s*\[', result, re.MULTILINE)
    root, tables = (result[:boundary.start()], result[boundary.start():]) if boundary else (result, '')
    for key in ROOT_KEYS:
        root = re.sub(r'^' + key + r'\s*=.*(?:\n|$)', '', root, flags=re.MULTILINE)
    values = ''.join(f'{key} = {json.dumps(native[key], ensure_ascii=False)}\n'
                     for key in ROOT_KEYS if key in native)
    # An inactive bridge table may have existed before this switch.
    provider = native.get('model_providers', {}).get(PROVIDER)
    if provider is not None:
        # Use the exact generated table syntax, including its original values.
        match = re.search(r'^\[model_providers\.(?:"codex-hybrid"|codex-hybrid)\][^\n]*\n', baseline, re.MULTILINE)
        if not match:
            raise ConfigError('CLIENT_CONFIG_REWRITE_UNSAFE')
        following = re.search(r'^\s*\[', baseline[match.end():], re.MULTILINE)
        end = match.end() + following.start() if following else len(baseline)
        tables += '\n' + baseline[match.start():end]
    # The root/table separators belong to this rewrite. Keep them stable
    # across repeated enable/disable cycles instead of retaining empty lines
    # left by the removed provider table.
    root = root.rstrip('\r\n')
    tables = tables.strip('\r\n')
    result = values + root + ('\n' if root else '') + (tables + '\n' if tables else '')
    expected = copy.deepcopy(before)
    for key in ROOT_KEYS:
        expected.pop(key, None)
        if key in native:
            expected[key] = native[key]
    expected.get('model_providers', {}).pop(PROVIDER, None)
    if provider is not None:
        expected.setdefault('model_providers', {})[PROVIDER] = provider
    if expected.get('model_providers') == {}:
        expected.pop('model_providers')
    if tomllib.loads(result) != expected:
        raise ConfigError('CLIENT_CONFIG_REWRITE_UNSAFE')
    return result


def retain_config_model(target, current):
    """CLI snapshots may be old; retain the user's current root model/absence."""
    before = tomllib.loads(current.decode('utf-8'))
    expected = tomllib.loads(target.decode('utf-8'))
    if ('model' in before) == ('model' in expected) and before.get('model') == expected.get('model'):
        return target
    text = target.decode('utf-8')
    boundary = re.search(r'^\s*\[', text, re.MULTILINE)
    root, tables = (text[:boundary.start()], text[boundary.start():]) if boundary else (text, '')
    root = re.sub(r'''^[ \t]*(?:model|"model"|'model')[ \t]*=.*(?:\n|$)''', '', root, flags=re.MULTILINE)
    expected.pop('model', None)
    if 'model' in before:
        root = 'model = ' + json.dumps(before['model']) + '\n' + root
        expected['model'] = before['model']
    result = root + tables
    if tomllib.loads(result) != expected:
        raise ValueError('无法安全保留当前模型配置，未切换接入。')
    return result.encode('utf-8')


